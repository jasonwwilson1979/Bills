# SECURITY WARNING: keep the secret key used in production secret!
def _load_secret_key():
    """Resolve SECRET_KEY without hard-coding anything insecure:

    1. DJANGO_SECRET_KEY environment variable (highest priority)
    2. an auto-generated key persisted next to the database, so container
       restarts keep their sessions/CSRF (created automatically on first use)
    3. an ephemeral generated key as a last resort (read-only filesystems)
    """
    import secrets as _secrets

    key = os.environ.get('DJANGO_SECRET_KEY', '')
    if key:
        return key

    secret_file = os.environ.get('DJANGO_SECRET_KEY_FILE', '')
    if not secret_file:
        db_path = os.environ.get('DJANGO_DB_PATH', str(BASE_DIR / 'db.sqlite3'))
        secret_file = os.path.join(os.path.dirname(db_path), 'secret_key')

    try:
        if os.path.exists(secret_file):
            with open(secret_file, 'r') as fh:
                key = fh.read().strip()
        if not key:
            key = _secrets.token_urlsafe(50)  # base64url: no $ {} \ chars
            os.makedirs(os.path.dirname(secret_file), exist_ok=True)
            with open(secret_file, 'w') as fh:
                fh.write(key)
            print('[BillFlow] generated a persistent secret key at ' + secret_file)
    except OSError:
        key = _secrets.token_urlsafe(50)  # cannot persist -> ephemeral
    return key


SECRET_KEY = _load_secret_key()

